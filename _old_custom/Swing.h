#ifndef __SWING_H
#define __SWING_H

#include <stdint.h>

/**
 * 旋转倒立摆 任务1 起摆控制器 —— 有界臂位置伺服 + 全同相(真泵)换向 (确定版, 真模型仿真已证明)
 * =====================================================================================
 * 设计铁律(用户): 水平臂【只能往复】, 绝不单方向转圈; 摆杆越泵越高(过 ±60° 达标即制动交卷).
 *
 * ★ 本版为什么是"确定版"(2026-07-15 重写, 已用相位敏感 Furuta 模型全场景验证) ★
 *   之前的"能量 bang-bang"把电机当力矩用, 每 5ms 按 sign(θ̇·cosθ) 翻向给满 PWM。
 *   电位器 θ̇ 有噪声 -> 方向每拍乱翻 -> 电机只是嗡嗡抖、臂几乎不动 -> "完全不泵"。
 *
 *   确定版换成【有界臂位置伺服 + 全同相(真泵)换向】(Spong 能量法 τ∝sign(θ̇·cosθ) 精神):
 *     1) 臂 = PD 位置伺服, 目标钉在 ±L_DEG(±90°)。结构上 |臂|≈±90°, 绝不转圈(不是靠事后刹车)。
 *     2) 全同相换向(真·泵能): 摆杆每次过底点(θ=0, 符号翻转)都把臂目标设在
 *        "摆杆当前运动方向的同侧极限":
 *          -→+ 过零(θ̇>0, 摆杆朝+) -> target=+L (臂朝+加速, 同相)
 *          +→- 过零(θ̇<0, 摆杆朝-) -> target=-L (臂朝-加速, 同相)
 *        两种过零都动作且都同相 -> 全周期顺相位注入能量, 摆幅单调增大, 必过60°。
 *        旧版"半泵半泄"只在一种过零翻 target -> 半周泵半周泄, 净泵弱(高摩擦慢一倍)。
 *     3) 臂做干净的大幅度往复扫动(真在泵能), 对电位器噪声极不敏感 -> 上板即用。
 *
 *   真模型仿真结论(sim_armservo_v2.py, 相位敏感联立 Furuta 方程, 电机转速上限进 rk4 子步, 含达标刹停):
 *     · 全同相 + 防死锁 + 硬踢: 名义 t60=0.3s(摆幅263.7°); 高摩擦 t60=2.1s(摆幅64.7°);
 *       臂累计均 ≤122° -> 往复OK, 绝不转圈。
 *     · 半泵半泄(旧): 高摩擦 t60=4.5s, 慢一倍。
 *     · 无硬踢/无防死锁: 摆杆静止不过零 -> 臂卡死 20.7° 失败(印证"转半圈就停"=死锁, 非相位)。
 *   注: 固件到 60° 即刹车交卷, 实际根本荡不到 100° -> 余量巨大。
 *
 * ★ 自动极性自纠已移除 ★
 *   全同相下两种初始极性都能泵(仿真已证), 旧"每6s看峰值翻极性"的逻辑纯属多余, 已从 Swing.c 删除。
 *   (Swing_GetFlips() 现恒返回 0, 仅为兼容 main.c 的 F: 显示位。)
 *
 * ★ 约定(已核对固件) ★
 *   - Pendulum_GetAngle()   = 滤波后 θ(度), 0°=自然下垂, ±180°=倒立。
 *   - Pendulum_GetSpeed()   = θ̇(度/秒, 已滤波)。
 *   - Pendulum_GetArmAngle()= TIM3 编码器累加臂角(度) —— 本版核心反馈(伺服臂位置)。
 *   - Motor_SetSpeed(+)     = 正转(PB12=0/PB13=1); Motor_Brake() = 硬短路制动。
 *
 * ★ 旋钮(基本不用动, 已给好仿真最优值) ★
 *   - L_DEG   : 臂往复幅度目标(度)。摆不上->加大(100~110); 撞机械限位->减小(70~80)。
 *   - KP_FW   : 臂位置伺服比例(%/度)。臂太肉->加大; 抖->减小。
 *   - KD_FW   : 臂速阻尼(%/(度/s))。臂冲过头/振荡->加大。
 *   - PWM_MAX : 占空比上限。
 *
 * 状态: 0=停止, 1=运行中(泵摆), 4=达标停机(屏 OK60), 3=超时失败, 5=失控(硬停机)。
 * 每 5ms 由 TIM4 中断调用 Swing_Tick(theta_deg, theta_dot_dps)。
 */

// ---- 臂位置伺服(核心) ----
#define L_DEG           90.0f   // 臂往复幅度目标(度): 臂在 ±90° 之间来回扫, 结构上不转圈
#define KP_FW           22.0f   // 臂位置伺服比例(%/度): 误差>4.3°即满占空比冲向目标。v2 由14提到22:
                              //   高摩擦时泵得更狠(仿真25×摩擦工况仍稳过64°, 余量足), 臂累计仅~112°不转圈
#define KD_FW           0.9f    // 臂速阻尼(%/(度/s)): 近目标减速防冲过 L(=Kd0.5 rad换算)
#define PWM_MAX         95      // 占空比上限(0~100)
#define RATE_A          0.5f    // 臂速 EMA 系数(抗 52 线编码器量化跳变)

// ---- 全同相换向(真泵) ----
#define COMMUT_DIR0     (+1)    // 初始臂目标极性(+1: 起步先扫向 +L; 全同相下两种极性都能泵, 此值仅定起步方向)

// ---- 臂硬上限 / 失控保护(往复的最后铁闸) ----
#define ARM_HARD_DEG    150.0f  // 臂角软上限: 超此强拉回中心(仿真最大仅~122°, 150 留足余量不误触)
#define RUNAWAY_ARM_DEG   300.0f // 臂净角超 ±300° -> 失控硬停机(正常绝不该到)
#define RUNAWAY_DIR_TICKS 260u   // 臂持续单方向转超 260 拍(≈1.3s) -> 失控

// ---- 防死锁(v2 关键修复) + 启动硬踢 ----
#define ARM_ARR_TOL     8.0f   // 臂"已到达目标"容差(°): |臂-target|<此即视为到位
#define DWELL_TICKS     120u    // 臂到位后若 >0.6s 仍无摆杆过零 -> 强制翻 target(永不卡死)
#define KICK_TICKS      40u     // 启动硬踢时长(≈200ms): 确定性甩臂打破下垂对称
#define KICK_PWM        95      // 启动硬踢占空比(0~100): 满占空比甩, 确保把摆杆踢起来
#define KICK_DIR        (+1)    // 启动硬踢方向(+1/-1): 若实测臂往错误边甩, 改这里

// ---- 自动极性(已废弃, 全同相必然泵、翻转无意义; 保留占位避免误用) ----
// 对应自纠逻辑已从 Swing.c 删除; Swing_GetFlips() 现恒返回 0(兼容 main.c 的 F: 位)。
#define POLARITY_TEST_MS  6000u  // [废弃] 旧: 每 6s 检查一次摆杆峰值摆幅
#define APEX_FLOOR       40.0f  // [废弃] 旧: 窗口内峰值摆幅低于此 -> 翻转换向极性
#define MAX_FLIPS          3u     // [废弃] 旧: 最多翻转换向次数

// ---- 任务 / 超时 / 达标 ----
#define TASK1_ANGLE_DEG 60.0f   // 任务1达标: |θ|≥60°
#define TIMEOUT_MS      30000u    // 30s 未到 ±60° -> 失败
#define OK_HOLD_TICKS  20u      // |θ|≥60° 需连续 20 拍(=100ms) 才确认达标(去抖)

void Swing_Init(void);
void Swing_Start(void);
void Swing_Stop(void);
void Swing_Tick(float theta_deg, float theta_dot_dps); // 每 5ms 由 TIM4 中断调用
uint8_t  Swing_GetState(void);   // 0=空闲 1=运行中 4=达标停机 3=超时失败 5=失控
uint32_t Swing_GetTimeMs(void);
float    Swing_GetPeak(void);    // 运行峰值 |摆角|
uint8_t  Swing_Looped(void);    // 是否进入竖直圆周(|θ|>=150°)
uint8_t  Swing_Ok(void);        // 任务1达标(|θ|>=60°)
float    Swing_GetArmActual(void); // 诊断: 当前臂角(°)
float    Swing_GetArmP2P(void);   // 诊断: 臂最近2s峰峰值摆幅(°, 应≈180=臂在满幅往复)
int8_t   Swing_GetPumpSign(void);// 诊断: 当前换向极性(+1/-1)
uint8_t  Swing_EncOk(void);     // 诊断: 编码器是否接好
uint8_t  Swing_GetRunaway(void); // 诊断: 是否触发失控保护(状态5)
uint8_t  Swing_GetFlips(void);  // 诊断: 已自动翻转换向极性次数

#endif
